// требушет: осадными они не считаются, но людей внутри них всё равно нет.
func (sp UnitSpec) Mechanism() bool { return sp.Engine || sp.Machine }

func Spec(t UnitType) UnitSpec {
	if t < unitTypeCount {
		return specs[t]
	}
	return UnitSpec{}
}

// AllSpecs отдаётся клиенту, чтобы интерфейс не дублировал баланс.
func AllSpecs() []UnitSpec {
	out := make([]UnitSpec, 0, unitTypeCount)
	for i := UnitType(0); i < unitTypeCount; i++ {
		out = append(out, specs[i])
	}
	return out
}

// Что можно купить каждой стороне. Разведчики доступны обоим.
// Короля в списках нет: он не наёмник, а приз осады.
var (
	AttackerBuyable = []UnitType{UnitInfantry, UnitScout, UnitSapper, UnitLadder, UnitRam, UnitBomber, UnitCatapult, UnitSiegeTower, UnitHealer}
	DefenderBuyable = []UnitType{UnitScout, UnitGarrison, UnitBallista, UnitTrebuchet, UnitEngineer, UnitHealer}
	// Элиту покупают обе стороны — но только за серебро.
	EliteBuyable = []UnitType{UnitCrossbow, UnitKnight}
)

func canBuy(side Side, t UnitType) bool {
	for _, x := range buyListFor(side) {
		if x == t {
			return true
		}
	}
	return false
}

// buyListFor — что доступно стороне: свои войска плюс общая элита.
func buyListFor(side Side) []UnitType {
	switch {
	case side.IsAttacker():
		return append(append([]UnitType{}, AttackerBuyable...), EliteBuyable...)
	case side == SideDefender:
		return append(append([]UnitType{}, DefenderBuyable...), EliteBuyable...)
	}
	return nil
}

// Buyable отдаёт клиенту список покупок для стороны.
func Buyable(side Side) []string {
	list := buyListFor(side)
	out := make([]string, 0, len(list))
	for _, t := range list {
		out = append(out, t.String())
	}
	return out
}
