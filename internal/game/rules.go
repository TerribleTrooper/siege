// Side — чья фигура. Это роль, а не игрок: роли закреплены за местами на
// всю партию (см. SeatOf).
type Side uint8

const (
	SideNeutral Side = iota
	SideDefender
	SideAttackerA
	SideAttackerB
)

func (s Side) IsAttacker() bool { return s == SideAttackerA || s == SideAttackerB }

func (s Side) String() string {
	switch s {
	case SideDefender:
		return "defender"
	case SideAttackerA:
		return "attackerA"
	case SideAttackerB:
		return "attackerB"
	}
	return "neutral"
}

// SideByName — обратное к String: в снимке сторона приезжает строкой, а
// боту, который читает снимок, нужна она сама.
func SideByName(name string) Side {
	for _, s := range []Side{SideDefender, SideAttackerA, SideAttackerB} {
		if s.String() == name {
			return s
		}
	}
	return SideNeutral
}

